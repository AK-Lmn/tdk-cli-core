import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { DiscoveredResource, DiscoveredStack } from "../../types/index.js";
import {
  clearMetadataCache,
  discoverResourcesWithProblems,
  getResourceMetadata,
  getStackMetadata,
  resetPrintedServiceWarnings,
  warnAboutSkippedFiles,
} from "../services.js";

const tempRoots: string[] = [];

function writeProject(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "tdk-services-metadata-"));
  tempRoots.push(root);
  for (const [relative, content] of Object.entries(files)) {
    const fullPath = join(root, relative);
    mkdirSync(dirname(fullPath), { recursive: true });
    writeFileSync(fullPath, content);
  }
  return root;
}

function resourceAt(serviceDir: string, overrides: Partial<DiscoveredResource> = {}) {
  return {
    name: "orders-api",
    path: serviceDir,
    configPath: join(serviceDir, "service.json"),
    stack: "shop",
    config: { appName: "orders-api", appType: "backend" },
    ...overrides,
  } as DiscoveredResource;
}

const validManifest = JSON.stringify({ appName: "orders-api", appType: "backend" });

beforeEach(() => {
  clearMetadataCache();
  resetPrintedServiceWarnings();
  vi.spyOn(console, "warn").mockImplementation(() => {});
});

afterEach(() => {
  vi.restoreAllMocks();
  for (const root of tempRoots.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

describe("getResourceMetadata", () => {
  it("reports tooling and generated files that sit next to the service manifest", () => {
    const root = writeProject({
      "services/orders-api/service.json": validManifest,
      "services/orders-api/Dockerfile": "FROM oven/bun\n",
      "services/orders-api/Tiltfile": "docker_build('orders-api', '.')\n",
      "services/orders-api/docker-compose.yml": "services: {}\n",
      "services/orders-api/vite.config.ts": "export default {}\n",
      "services/orders-api/prisma/schema.prisma": "model Order { id Int @id }\n",
    });
    const serviceDir = join(root, "services", "orders-api");

    const metadata = getResourceMetadata(resourceAt(serviceDir));

    expect(metadata.hasDockerfile).toBe(true);
    expect(metadata.hasTiltfile).toBe(true);
    expect(metadata.hasDockerCompose).toBe(true);
    const byName = new Map(metadata.autogeneratedFiles.map((file) => [file.name, file]));
    expect([...byName.keys()]).toEqual(
      expect.arrayContaining([
        "Dockerfile",
        "Tiltfile",
        "docker-compose.yml",
        "vite.config.ts",
        "prisma/schema.prisma",
      ]),
    );
    expect(byName.get("Dockerfile")?.type).toBe("docker");
    expect(byName.get("Tiltfile")?.type).toBe("tilt");
    expect(byName.get("vite.config.ts")?.type).toBe("config");
    expect(byName.get("prisma/schema.prisma")?.type).toBe("prisma");
    expect(byName.get("Dockerfile")?.size).toBeGreaterThan(0);
  });

  it("leaves dependencies empty when the manifest declares none", () => {
    const root = writeProject({ "services/orders-api/service.json": validManifest });

    const metadata = getResourceMetadata(resourceAt(join(root, "services", "orders-api")));

    expect(metadata.dependencies).toEqual([]);
    expect(metadata.status).toBe("unknown");
  });

  it("carries declared dependencies through to the metadata", () => {
    const root = writeProject({ "services/orders-api/service.json": validManifest });

    const metadata = getResourceMetadata(
      resourceAt(join(root, "services", "orders-api"), {
        config: { appName: "orders-api", appType: "backend", dependsOn: ["postgres"] },
      }),
    );

    expect(metadata.dependencies).toEqual(["postgres"]);
  });

  it("infers frontend and library types when the manifest omits appType", () => {
    const root = writeProject({
      "web-frontend/service.json": validManifest,
      "shared-lib/service.json": validManifest,
      "infra-tools/service.json": validManifest,
    });

    const frontend = getResourceMetadata(
      resourceAt(join(root, "web-frontend"), { name: "web-frontend", config: undefined }),
    );
    const library = getResourceMetadata(
      resourceAt(join(root, "shared-lib"), { name: "shared-lib", config: undefined }),
    );
    const infra = getResourceMetadata(
      resourceAt(join(root, "infra-tools"), { name: "infra-tools", config: undefined }),
    );

    expect(frontend.type).toBe("frontend");
    expect(library.type).toBe("library");
    expect(infra.type).toBe("library");
  });

  it("prefers the configured appType over name based inference", () => {
    const root = writeProject({ "jobs-frontend/service.json": validManifest });

    const metadata = getResourceMetadata(
      resourceAt(join(root, "jobs-frontend"), {
        name: "jobs-frontend",
        config: { appName: "jobs-frontend", appType: "worker" },
      }),
    );

    expect(metadata.type).toBe("worker");
  });

  it("reuses the cached metadata until the cache is cleared", () => {
    const root = writeProject({ "services/orders-api/service.json": validManifest });
    const resource = resourceAt(join(root, "services", "orders-api"));

    const first = getResourceMetadata(resource);
    const second = getResourceMetadata(resource);
    clearMetadataCache();
    const third = getResourceMetadata(resource);

    expect(second).toBe(first);
    expect(third).not.toBe(first);
    expect(third).toEqual(first);
  });
});

describe("getStackMetadata", () => {
  it("aggregates resource counts and spans every resource timestamp", () => {
    const root = writeProject({
      "services/orders-api/service.json": validManifest,
      "services/orders-worker/service.json": validManifest,
    });
    const resources = [
      resourceAt(join(root, "services", "orders-api")),
      resourceAt(join(root, "services", "orders-worker"), {
        name: "orders-worker",
        config: { appName: "orders-worker", appType: "worker" },
      }),
    ];
    const stack: DiscoveredStack = {
      name: "shop",
      description: "2 resources",
      resources,
      resourceCount: resources.length,
    };

    const metadata = getStackMetadata(stack);

    const resourceMetadata = resources.map((entry) => getResourceMetadata(entry));
    expect(metadata.resourceCount).toBe(2);
    expect(metadata.resources).toHaveLength(2);
    expect(metadata.createdAt).toBe(
      new Date(
        Math.min(...resourceMetadata.map((r) => new Date(r.createdAt).getTime())),
      ).toISOString(),
    );
    expect(metadata.lastModified).toBe(
      new Date(
        Math.max(...resourceMetadata.map((r) => new Date(r.lastModified).getTime())),
      ).toISOString(),
    );
    expect(metadata.overallStatus).toBe("unknown");
    expect(getStackMetadata(stack)).toBe(metadata);
  });
});

describe("discoverResourcesWithProblems", () => {
  it("keeps the valid manifests and reports one problem per broken file", () => {
    const root = writeProject({
      "services/good/service.json": validManifest,
      "services/broken/service.json": "{ not json",
      "services/incomplete/service.json": JSON.stringify({ description: "no name" }),
    });

    const { resources, problems } = discoverResourcesWithProblems(root);

    expect(resources.map((resource) => resource.name)).toEqual(["orders-api"]);
    expect(problems).toHaveLength(2);
    const reasons = problems.map((problem) => problem.reason).join("\n");
    expect(reasons).toContain("invalid JSON");
    expect(reasons).toContain("missing required fields");
  });

  it("names the route field that is not a string", () => {
    const root = writeProject({
      "services/good/service.json": validManifest,
      "services/routed/service.json": JSON.stringify({
        appName: "routed",
        appType: "backend",
        apiPath: 42,
      }),
    });

    const { resources, problems } = discoverResourcesWithProblems(root);

    expect(resources).toHaveLength(1);
    expect(problems).toHaveLength(1);
    expect(problems[0]?.reason).toContain("apiPath: expected a string");
  });
});

describe("warnAboutSkippedFiles", () => {
  const problems = [{ path: "services/broken/service.json", reason: "invalid JSON" }];

  it("prints each skipped file once even when discovery runs again", () => {
    warnAboutSkippedFiles(problems);
    warnAboutSkippedFiles(problems);

    expect(console.warn).toHaveBeenCalledTimes(1);
    expect(console.warn).toHaveBeenCalledWith(expect.stringContaining("skipped"));
    expect(console.warn).toHaveBeenCalledWith(expect.stringContaining("invalid JSON"));
  });

  it("prints again after the warning state is reset", () => {
    warnAboutSkippedFiles(problems);
    resetPrintedServiceWarnings();
    warnAboutSkippedFiles(problems);

    expect(console.warn).toHaveBeenCalledTimes(2);
  });
});
